local mm = require('oemm').new('/etc/oemm/mm1/init.lua')
mm:registerType({}, 'furnace')
mm:registerMachine('furnace', {})
mm:registerMachine('furnace', {})
local older = mm:alloc('furnace')
local newer, busy = mm:alloc('furnace')
assert(mm:free(older))
assert(not pcall(function() mm:free(older) end))
assert(#mm:listFree('furnace') == 1 and mm:listOccupied('furnace')[1] == busy)
assert(mm:free(newer))
