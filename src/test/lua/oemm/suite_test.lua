local kind = require('oemm.suite.MachineType'):new()
kind:slot('in')
kind:slot('out')
kind:func('status')
local machine = require('oemm.suite.Machine'):new(kind)
assert(not machine:check() and not pcall(function() machine:assert() end))
assert(not pcall(function() machine:slot('invalid', 'controller', 1) end))
machine:slot('in', 'controller', 2)
machine:slot('out', 'controller', 3)
machine:func('status', function(x) return x + 1 end)
machine:assert()
local slots = {[3] = {registry_name = 'iron', num = 1}}
local card = oc.switchingCard({controller = slots})
assert(machine:peek(card, 'out').num == 1)
assert(machine:pop(card, 'out', 1) and machine:push(card, 'in'))
assert(not slots[3] and slots[2].num == 1 and machine:invoke('status', 4) == 5)
