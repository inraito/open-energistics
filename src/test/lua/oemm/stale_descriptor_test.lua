local mm = require('oemm').new('/etc/oemm/mm1/init.lua')
mm:registerType({}, 'furnace')
local machine = {}
mm:registerMachine('furnace', machine)
local old = mm:alloc('furnace')
assert(mm:free(old))
local active = mm:alloc('furnace')
assert(active ~= old)
pcall(function() mm:free(old) end)
assert(#mm:listFree('furnace') == 0, 'expired descriptor released the current owner\'s machine')
